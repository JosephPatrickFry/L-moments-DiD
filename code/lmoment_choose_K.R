# ================================================================
# Choosing the number of L-moments K by minimizing an unbiased risk
# estimate (notes "Choosing K", Section 4 end / Lemmas 3-4).
#
# With Q_hat_K = sum_{j<=K} theta_hat_j phi_j and phi_j orthonormal on
# L2(0,1), Parseval gives
#   E || Q_hat_K - Q ||^2 = sum_{j<=K} V_j - sum_{j<=K} theta_j^2 + int Q^2,
# so it suffices to minimize R(K) = sum_{j<=K} (V_j - theta_j^2), estimated
# without bias by
#   R_hat(K) = sum_{j<=K} [ theta_hat_j^2 - 2 M_j ],   E[M_j] = theta_j^2.
# M_j (the less computationally intensive version): draw N random
# partitions of the sample into two disjoint halves (A_r, B_r) and set
#   M_j = (1/N) sum_r theta_hat_j(A_r) theta_hat_j(B_r);
# the halves are independent and the U-statistic estimator is unbiased,
# so each product is unbiased for theta_j^2.
#
# Basis. L-moments are coefficients on the shifted Legendre polynomials
# P*_{j-1}, which are orthogonal with ||P*_{j-1}||^2 = 1/(2j-1). The
# orthonormal basis is phi_j = sqrt(2j-1) P*_{j-1}, with coefficients
#   theta_j = sqrt(2j-1) * lambda_j,  Q = sum_j theta_j phi_j.
# Parseval (and hence the risk identity) holds for theta, so
# basis = "orthonormal" is the default; basis = "lmoment" uses the raw
# L-moments lambda_j (no rescaling).
# Selection: K_hat = argmin_{1<=K<=K_max} { R_hat(K) + B^2 K_max / sqrt(n) };
# the penalty does not depend on K, so it shifts the reported bound but
# not K_hat. Lemma 3 requires K_max <= n/2.
# Self-contained: all L-moments here come from lmom_u_stable(), so no
# other project file is needed. The choose-K simulation (sim_K_run.R)
# uses choose_K_lmoment(); lmom_M() and lmom_Rhat() are single-j / single-K
# conveniences used by test_lmoment_choose_K.R.
# ================================================================

# Numerically stable U-statistic L-moments for large K.
# lmom_u() maps probability-weighted moments to L-moments with
# coefficients up to ~1e43 at K = 60, so it loses all accuracy beyond
# K ~ 20. The same U-statistic is lambda_k = (1/n) sum_i w_k(i) x_(i),
# where w_k(i) = (-1)^(k-1) Q_{k-1}(i-1) and Q_m is the Hahn
# (alpha = beta = 0, i.e. discrete Legendre) polynomial on 0..n-1,
# generated by its three-term recurrence
#   -x Q_m = A_m Q_{m+1} - (A_m + C_m) Q_m + C_m Q_{m-1},
#   A_m = (m+1)(N-m) / (2(2m+1)),  C_m = m(m+N+1) / (2(2m+1)),  N = n-1.
# Checked against exact rational weights (bigz) to ~1e-9 for k <= 50.
lmom_u_stable <- function(x, K) {
  x <- sort(x[!is.na(x)])
  n <- length(x)
  stopifnot(n >= K)
  N <- n - 1; xi <- 0:N
  out <- numeric(K); Qm1 <- rep(0, n); Q <- rep(1, n)
  for (m in 0:(K - 1)) {
    out[m + 1] <- (-1)^m * sum(Q * x) / n
    if (m < K - 1) {
      A <- (m + 1) * (N - m) / (2 * (2 * m + 1)); C <- m * (m + N + 1) / (2 * (2 * m + 1))
      Qp <- ((A + C) * Q - C * Qm1 - xi * Q) / A
      Qm1 <- Q; Q <- Qp
    }
  }
  setNames(out, paste0("l", seq_len(K)))
}

basis_scale <- function(K, basis = c("orthonormal", "lmoment")) {
  basis <- match.arg(basis)
  if (basis == "orthonormal") sqrt(2 * seq_len(K) - 1) else rep(1, K)
}

# M_j for all j = 1..K at once, sharing the same N random partitions.
# Each partition splits x into halves of size floor(n/2) and ceiling(n/2).
lmom_M_all <- function(x, K, N = 200, basis = c("orthonormal", "lmoment"), seed = NULL) {
  x <- x[!is.na(x)]
  n <- length(x)
  stopifnot(floor(n / 2) >= K)
  if (!is.null(seed)) set.seed(seed)
  s <- basis_scale(K, basis)
  na <- floor(n / 2)
  prod_sum <- numeric(K)
  for (r in seq_len(N)) {
    a <- sample.int(n, na)
    prod_sum <- prod_sum + (s * lmom_u_stable(x[a], K)) * (s * lmom_u_stable(x[-a], K))
  }
  setNames(prod_sum / N, paste0("M", seq_len(K)))
}

# 1. M_j for a single j (uses the partition-based estimator)
lmom_M <- function(x, j, N = 200, basis = c("orthonormal", "lmoment"), seed = NULL) {
  unname(lmom_M_all(x, j, N = N, basis = basis, seed = seed)[j])
}

# 2. R_hat(K) = sum_{j<=K} [theta_hat_j^2 - 2 M_j]
#    lambda (full-sample L-moments) and M can be passed in to avoid recomputation.
lmom_Rhat <- function(x, K, M = NULL, lambda = NULL, N = 200,
                      basis = c("orthonormal", "lmoment"), seed = NULL) {
  basis <- match.arg(basis)
  if (is.null(lambda)) lambda <- lmom_u_stable(x, K)
  if (is.null(M)) M <- lmom_M_all(x, K, N = N, basis = basis, seed = seed)
  theta <- basis_scale(K, basis) * lambda[seq_len(K)]
  sum(theta^2 - 2 * M[seq_len(K)])
}

# 3. Choose K over 1..K_max by minimizing R_hat(K) + B^2 K_max / sqrt(n).
#    B: user-supplied bound on |X| (Lemma 4); K_max <= n/2.
choose_K_lmoment <- function(x, B, K_max, N = 200, basis = c("orthonormal", "lmoment"), seed = NULL) {
  basis <- match.arg(basis)
  x <- x[!is.na(x)]
  n <- length(x)
  stopifnot(K_max >= 1, K_max <= n / 2)
  # The U-statistic weights on extreme order statistics grow explosively
  # once k is a sizable fraction of the sample (exact max weight ~1.5 at
  # k = 100, n = 618; ~7e10 at k = 200), so lambda_hat_k and the
  # half-sample M_k become unusable well before Lemma 3's K_max <= n/2.
  if (K_max > 0.1 * floor(n / 2))
    warning(sprintf("K_max = %d exceeds 10%% of the half-sample size (%d): high-order estimates may be unstable",
                    K_max, floor(n / 2)))
  if (max(abs(x)) > B) warning(sprintf("max|x| = %.4g exceeds the supplied B = %.4g", max(abs(x)), B))
  lambda <- lmom_u_stable(x, K_max)
  M <- lmom_M_all(x, K_max, N = N, basis = basis, seed = seed)
  theta <- basis_scale(K_max, basis) * lambda
  Rhat <- cumsum(theta^2 - 2 * M)                     # R_hat(K), K = 1..K_max
  penalty <- B^2 * K_max / sqrt(n)
  crit <- Rhat + penalty
  K_hat <- which.min(crit)
  list(K = K_hat,
       table = data.frame(K = seq_len(K_max), lambda = lambda, theta = theta, M = M,
                          Rhat = Rhat, penalty = penalty, criterion = crit),
       risk_bound = crit[K_hat], penalty = penalty, n = n, basis = basis, N = N)
}
